object AppStrings {

    /**
     * Resolves the localized string for [key] in [language].
     * Falls back to English if the translation is missing.
     */
    fun get(key: UiTextKey, language: SttLanguage = SttLanguage.ENGLISH): String {
        val langMap = when (language) {
            SttLanguage.ENGLISH -> englishStrings
            SttLanguage.HINDI -> hindiStrings
            SttLanguage.MARATHI -> marathiStrings
            SttLanguage.GUJARATI -> gujaratiStrings
            SttLanguage.KANNADA -> kannadaStrings
            SttLanguage.MALAYALAM -> malayalamStrings
            SttLanguage.TAMIL -> tamilStrings
            SttLanguage.TELUGU -> teluguStrings
            SttLanguage.BENGALI -> bengaliStrings
            SttLanguage.ODIA -> odiaStrings
        }
        return langMap[key] ?: englishStrings[key] ?: key.name
    }

    /**
     * Resolves the localized string by [languageCode] (e.g. "hi", "mr", "en").
     */
    fun get(key: UiTextKey, languageCode: String): String {
        val lang = SttLanguage.fromCode(languageCode) ?: SttLanguage.ENGLISH
        return get(key, lang)
    }

    /**
     * Resolves and formats a parameterized localized string.
     */
    fun format(key: UiTextKey, language: SttLanguage = SttLanguage.ENGLISH, vararg args: Any): String {
        val template = get(key, language)
        return try {
            String.format(template, *args)
        } catch (_: Exception) {
            template
        }
    }

